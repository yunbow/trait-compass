/**
 * カテゴリスコア(0〜100)を「高め/やや高め/低め」の3段階の質的表現に変換する(P0対応)。
 *
 * これまで「100%」のようなパーセンテージをそのまま表示していたが、精密な検査結果のように
 * 読まれる懸念(「100%問題がある」「判定精度100%」等の誤解)があったため、質的な表現に
 * 置き換える。境界値(33/34, 66/67)は3件法の回答(0/1/2)を均等な3分割に近づけたもの。
 */
export type ScoreLevel = "高め" | "やや高め" | "低め";

export function scoreToLevel(score: number): ScoreLevel {
  if (score >= 67) return "高め";
  if (score >= 34) return "やや高め";
  return "低め";
}
